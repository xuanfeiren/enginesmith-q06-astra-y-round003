// Qwen3-0.6B inference engine for one logical NeuronCore (Trainium2, LNC=2), EngineSmith protocol 1.
//
//   engine --model MODEL_DIR        requests on stdin, replies on stdout, one JSON object per line
//
// Every layer of the model runs on the NeuronCores as NKI kernels compiled to NEFFs at build time and embedded in
// this executable (neffs.S): a layered prefill (pf_emb, pf_layer x 27 on per-layer tensor slices, pf_kv: the last
// layer's KV cache writes, pf_tail: the last layer for the last prompt token + LM head + argmax) for prompt buckets
// 256 / 1,024 / 4,096, and one NEFF per decode step (28 layers,
// LM head, argmax) per static attention bucket. The host loads and re-lays out the weights once, then only writes
// the prompt, queues executions (nrta_execute_schedule) and reads the generated tokens once per request.
//
// Device state shared by all NEFFs (bound by name): weights, kcache / vcache, toks (token history: toks[t + 1] is the
// token predicted after position t), prompt, plen, and the position ping-pong buffers posX / posY (a decode step
// reads one and writes pos + 1 into the other).
