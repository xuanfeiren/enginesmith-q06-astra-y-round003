// Minimal JSON (requests and the safetensors header)
struct JVal {
  enum T { NUL, BOOL, NUM, STR, ARR, OBJ } t = NUL;
  bool b = false; double n = 0; std::string s; std::vector<JVal> a; std::vector<std::pair<std::string, JVal>> o;
  const JVal* get(const std::string& k) const { for (auto& kv : o) if (kv.first == k) return &kv.second; return nullptr; }
};
struct JParser {
  const char* p; const char* e;
  void ws() { while (p < e && (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')) p++; }
  [[noreturn]] void fail() { throw std::runtime_error("bad JSON"); }
  std::string str() {
    if (*p != '"') fail();
    p++; std::string r;
    while (p < e && *p != '"') {
      if (*p == '\\') {
        p++; if (p >= e) fail();
        char c = *p++;
        switch (c) {
          case 'n': r += '\n'; break; case 't': r += '\t'; break; case 'r': r += '\r'; break;
          case 'b': r += '\b'; break; case 'f': r += '\f'; break;
          case 'u': { if (e - p < 4) fail(); unsigned v = std::stoul(std::string(p, 4), nullptr, 16); p += 4;
                      if (v < 0x80) r += (char)v; else if (v < 0x800) { r += (char)(0xC0 | (v >> 6)); r += (char)(0x80 | (v & 63)); }
                      else { r += (char)(0xE0 | (v >> 12)); r += (char)(0x80 | ((v >> 6) & 63)); r += (char)(0x80 | (v & 63)); } break; }
          default: r += c;
        }
      } else r += *p++;
    }
    if (p >= e) fail();
    p++; return r;
  }
  JVal val() {
    ws(); if (p >= e) fail();
    JVal v;
    if (*p == '{') {
      v.t = JVal::OBJ; p++; ws();
      if (*p == '}') { p++; return v; }
      while (true) { ws(); std::string k = str(); ws(); if (*p != ':') fail(); p++; v.o.emplace_back(k, val()); ws();
                     if (*p == ',') { p++; continue; } if (*p == '}') { p++; break; } fail(); }
    } else if (*p == '[') {
      v.t = JVal::ARR; p++; ws();
      if (*p == ']') { p++; return v; }
      while (true) { v.a.push_back(val()); ws(); if (*p == ',') { p++; continue; } if (*p == ']') { p++; break; } fail(); }
    } else if (*p == '"') { v.t = JVal::STR; v.s = str(); }
    else if (!strncmp(p, "true", 4)) { v.t = JVal::BOOL; v.b = true; p += 4; }
    else if (!strncmp(p, "false", 5)) { v.t = JVal::BOOL; p += 5; }
    else if (!strncmp(p, "null", 4)) { p += 4; }
    else { char* q; v.t = JVal::NUM; v.n = strtod(p, &q); if (q == p) fail(); p = q; }
    return v;
  }
};
static JVal parse_json(const char* s, size_t n) { JParser jp{s, s + n}; JVal v = jp.val(); return v; }

// ---------------------------------------------------------------------------------------------------------------
// Safetensors (mmap, bf16)
struct SafeTensors {
  struct T { const uint16_t* data; std::vector<int64_t> shape; };
  std::map<std::string, T> t;
  void open_file(const std::string& path) {
    int fd = ::open(path.c_str(), O_RDONLY); if (fd < 0) die("cannot open " + path);
    struct stat st; fstat(fd, &st);
    void* m = mmap(nullptr, st.st_size, PROT_READ, MAP_PRIVATE, fd, 0); if (m == MAP_FAILED) die("mmap " + path);
    close(fd);
    const char* base = (const char*)m; uint64_t n; memcpy(&n, base, 8);
    JVal h = parse_json(base + 8, n);
    for (auto& kv : h.o) {
      if (kv.first == "__metadata__") continue;
      const JVal* dt = kv.second.get("dtype"); const JVal* sh = kv.second.get("shape"); const JVal* off = kv.second.get("data_offsets");
      if (!dt || dt->s != "BF16") die("tensor " + kv.first + " is not BF16");
      T x; x.data = (const uint16_t*)(base + 8 + n + (size_t)off->a[0].n);
      for (auto& d : sh->a) x.shape.push_back((int64_t)d.n);
      t[kv.first] = x;
    }
  }
  const T& get(const std::string& name, std::vector<int64_t> shape) const {
    auto it = t.find(name); if (it == t.end()) die("missing tensor " + name);
    if (it->second.shape != shape) die("unexpected shape of " + name);
    return it->second;
  }
};
static float bf2f(uint16_t b) { uint32_t u = (uint32_t)b << 16; float f; memcpy(&f, &u, 4); return f; }
static uint16_t f2bf_exact(float f) { uint32_t u; memcpy(&u, &f, 4); return (uint16_t)(u >> 16); }  // only for -1/0/1

// Weight-stationary tile layout (kernels/qwen3_weights.py ws_layout) of a row-major W [N, K] (N out, K in), restricted
// to the output tiles `nts` and the K tiles `kts` of one core: dst[p, (i * nkt + k) * 128 + j] = W[nts[i] * 128 + j,
// kts[k] * 128 + p]; rows >= N are zero (LM head padding).
static void ws_tiles(uint16_t* dst, const uint16_t* W, int64_t N, int64_t K, const std::vector<int>& nts,
                     const std::vector<int>& kts) {
  size_t row = nts.size() * kts.size() * 128;
  for (int p = 0; p < 128; p++)
    for (size_t i = 0; i < nts.size(); i++)
      for (size_t k = 0; k < kts.size(); k++) {
        uint16_t* d = dst + p * row + (i * kts.size() + k) * 128;
        int64_t col = (int64_t)kts[k] * 128 + p;
        for (int j = 0; j < 128; j++) {
          int64_t r = (int64_t)nts[i] * 128 + j;
          d[j] = r < N ? W[r * K + col] : 0;
        }
      }
}
static std::vector<int> range(int a, int b) { std::vector<int> r; for (int i = a; i < b; i++) r.push_back(i); return r; }
static std::vector<int> cat(std::vector<int> a, const std::vector<int>& b) { a.insert(a.end(), b.begin(), b.end()); return a; }

// ---------------------------------------------------------------------------------------------------------------
// Device tensors
struct Dev {
  std::map<std::string, nrt_tensor_t*> t; std::map<std::string, size_t> sz;
  nrt_tensor_t* alloc(const std::string& name, size_t size) {
    auto it = t.find(name);
    if (it != t.end()) { if (sz[name] != size) die("size mismatch for " + name); return it->second; }
    nrt_tensor_t* x; CK(nrt_tensor_allocate(NRT_TENSOR_PLACEMENT_DEVICE, 0, size, name.c_str(), &x));
    t[name] = x; sz[name] = size; return x;
  }
  void write(const std::string& name, const void* data, size_t size) {
    nrt_tensor_t* x = alloc(name, size); CK(nrt_tensor_write(x, data, 0, size));
  }
  void zero(const std::string& name, size_t size) {
    nrt_tensor_t* x = alloc(name, size);
    std::vector<char> z(std::min<size_t>(size, 64 << 20), 0);
    for (size_t o = 0; o < size; o += z.size()) CK(nrt_tensor_write(x, z.data(), o, std::min(z.size(), size - o)));
  }
};

struct Exec { nrt_model_t* m; nrt_tensor_set_t* in; nrt_tensor_set_t* out; };

struct Engine {
  Dev dev;
  std::map<std::string, nrt_model_t*> models;
  std::map<int, Exec> stepA, stepB;            // per bucket: A reads posX writes posY, B the reverse
  std::map<int, std::vector<Exec>> prefill;    // per bucket: emb, 28 x layer, head
  int pos = -1;          // decode position held in the current pos buffer (-1: no state)
  bool posInX = true;    // which ping-pong buffer holds pos
  std::vector<NRT_STATUS> rets;

  nrt_model_t* model(const std::string& name) {
    auto it = models.find(name); if (it != models.end()) return it->second;
    for (int i = 0; i < neff_count; i++)
      if (name == neff_table[i].name) {
        nrt_model_t* m;
        CK(nrt_load(neff_table[i].start, neff_table[i].end - neff_table[i].start, 0, 1, &m));
        models[name] = m; return m;
      }
    die("NEFF not embedded: " + name);
    return nullptr;
  }

  // binding rules: name -> device tensor (whole or a per-layer slice)
  Exec bind(const std::string& neff, int layer, const std::map<std::string, std::string>& rename) {
    Exec e{model(neff), nullptr, nullptr};
    CK(nrt_allocate_tensor_set(&e.in)); CK(nrt_allocate_tensor_set(&e.out));
    nrt_tensor_info_array_t* info; CK(nrt_get_model_tensor_info(e.m, &info));
    for (uint64_t i = 0; i < info->tensor_count; i++) {
      auto& ti = info->tensor_array[i];
      bool in = ti.usage == NRT_TENSOR_USAGE_INPUT;
      std::string nm = ti.name;
      auto r = rename.find(nm); if (r != rename.end()) nm = r->second;
      auto it = dev.t.find(nm);
      if (it == dev.t.end()) die(neff + ": no device tensor for " + nm);
      size_t full = dev.sz[nm];
      nrt_tensor_t* x = it->second;
      if (full != ti.size) {
        if (layer >= 0 && full == (size_t)L * ti.size) {
          CK(nrt_tensor_allocate_slice(x, (size_t)layer * ti.size, ti.size, ti.name, &x));
        } else if (full > ti.size && (nm == "ids" || nm.rfind("s_", 0) == 0)) {
          CK(nrt_tensor_allocate_slice(x, 0, ti.size, ti.name, &x));   // max-size buffer, prefix used
        } else die(neff + ": size mismatch for " + nm);
      }
      CK(nrt_add_tensor_to_tensor_set(in ? e.in : e.out, ti.name, x));
    }
    nrt_free_model_tensor_info(info);
    return e;
  }

  void load_weights(const std::string& dir) {
    SafeTensors st; st.open_file(dir + "/model.safetensors");
    auto bf = [](size_t n) { return std::vector<uint16_t>(n); };
    const size_t H = HID;
    // embedding as is; LM head (vocab split over the two cores, padded to 2 x 594 tiles)
    const uint16_t* emb = st.get("model.embed_tokens.weight", {VOCAB, HID}).data;
    dev.write("embed", emb, (size_t)VOCAB * H * 2);
    const uint16_t* lm = st.t.count("lm_head.weight") ? st.get("lm_head.weight", {VOCAB, HID}).data : emb;
    {
      size_t per = (size_t)128 * NVL * 8 * 128; auto w = bf(2 * per);
      for (int c = 0; c < 2; c++) ws_tiles(w.data() + c * per, lm, VOCAB, HID, range(NVL * c, NVL * (c + 1)), range(0, 8));
      dev.write("wlm", w.data(), w.size() * 2);
    }
    auto col = [&](const uint16_t* v, int n, float* dst) {   // [n] -> [128, n/128] fp32: dst[p, kt] = v[kt*128 + p]
      int kt = n / 128; for (int p = 0; p < 128; p++) for (int k = 0; k < kt; k++) dst[p * kt + k] = bf2f(v[k * 128 + p]);
    };
    {
      std::vector<float> nf(1024); col(st.get("model.norm.weight", {HID}).data, HID, nf.data());
      dev.write("normf", nf.data(), nf.size() * 4);
    }
    std::vector<float> ln1(L * 1024), ln2(L * 1024), qn(L * 128), kn(L * 128);
    size_t sq = 128 * 16 * 8 * 128, so = 128 * 8 * 8 * 128, sgu = 128 * 24 * 8 * 128, sd = 128 * 8 * 12 * 128;
    size_t sop = 128 * 4 * 16 * 128, sdp = 128 * 4 * 24 * 128;
    auto wqkv = bf(L * 2 * sq), wo = bf(L * 2 * so), wgu = bf(L * 2 * sgu), wd = bf(L * 2 * sd);
    auto wop = bf(L * 2 * sop), wdp = bf(L * 2 * sdp);
    std::vector<uint16_t> qkv((size_t)4096 * H), gu((size_t)6144 * H);
    for (int l = 0; l < L; l++) {
      std::string p = "model.layers." + std::to_string(l) + ".";
      col(st.get(p + "input_layernorm.weight", {HID}).data, HID, &ln1[l * 1024]);
      col(st.get(p + "post_attention_layernorm.weight", {HID}).data, HID, &ln2[l * 1024]);
      const uint16_t* q = st.get(p + "self_attn.q_norm.weight", {128}).data;
      const uint16_t* k = st.get(p + "self_attn.k_norm.weight", {128}).data;
      for (int i = 0; i < 128; i++) { qn[l * 128 + i] = bf2f(q[i]); kn[l * 128 + i] = bf2f(k[i]); }
      memcpy(qkv.data(), st.get(p + "self_attn.q_proj.weight", {2048, HID}).data, 2048 * H * 2);
      memcpy(qkv.data() + 2048 * H, st.get(p + "self_attn.k_proj.weight", {1024, HID}).data, 1024 * H * 2);
      memcpy(qkv.data() + 3072 * H, st.get(p + "self_attn.v_proj.weight", {1024, HID}).data, 1024 * H * 2);
      memcpy(gu.data(), st.get(p + "mlp.gate_proj.weight", {3072, HID}).data, 3072 * H * 2);
      memcpy(gu.data() + 3072 * H, st.get(p + "mlp.up_proj.weight", {3072, HID}).data, 3072 * H * 2);
      const uint16_t* o = st.get(p + "self_attn.o_proj.weight", {HID, 2048}).data;
      const uint16_t* d = st.get(p + "mlp.down_proj.weight", {HID, 3072}).data;
      for (int c = 0; c < 2; c++) {
        size_t lc = (size_t)l * 2 + c;
        ws_tiles(&wqkv[lc * sq], qkv.data(), 4096, HID, cat(cat(range(8 * c, 8 * c + 8), range(16 + 4 * c, 20 + 4 * c)), range(24 + 4 * c, 28 + 4 * c)), range(0, 8));
        ws_tiles(&wo[lc * so], o, HID, 2048, range(0, 8), range(8 * c, 8 * c + 8));
        ws_tiles(&wgu[lc * sgu], gu.data(), 6144, HID, cat(range(12 * c, 12 * c + 12), range(24 + 12 * c, 36 + 12 * c)), range(0, 8));
        ws_tiles(&wd[lc * sd], d, HID, 3072, range(0, 8), range(12 * c, 12 * c + 12));
        ws_tiles(&wop[lc * sop], o, HID, 2048, range(4 * c, 4 * c + 4), range(0, 16));
        ws_tiles(&wdp[lc * sdp], d, HID, 3072, range(4 * c, 4 * c + 4), range(0, 24));
      }
    }
    dev.write("ln1", ln1.data(), ln1.size() * 4); dev.write("ln2", ln2.data(), ln2.size() * 4);
    dev.write("qn", qn.data(), qn.size() * 4); dev.write("kn", kn.data(), kn.size() * 4);
    dev.write("wqkv", wqkv.data(), wqkv.size() * 2); dev.write("wo", wo.data(), wo.size() * 2);
    dev.write("wgu", wgu.data(), wgu.size() * 2); dev.write("wd", wd.data(), wd.size() * 2);
    dev.write("wo_p", wop.data(), wop.size() * 2); dev.write("wd_p", wdp.data(), wdp.size() * 2);
    // RoPE: rotate-half matrix (R^T x = rotate_half(x)) and cos / sin tables (theta 1e6, fp64 -> fp32)
    std::vector<uint16_t> rot(128 * 128, 0);
    for (int m = 0; m < 64; m++) { rot[(m + 64) * 128 + m] = f2bf_exact(-1.0f); rot[m * 128 + m + 64] = f2bf_exact(1.0f); }
    dev.write("rot", rot.data(), rot.size() * 2);
    std::vector<float> cs((size_t)TMAX * 64), sn((size_t)TMAX * 64), csT((size_t)128 * TMAX), snT((size_t)128 * TMAX);
    for (int i = 0; i < 64; i++) {
      double inv = 1.0 / std::pow(1e6, (double)(2 * i) / 128.0);
      for (int t = 0; t < TMAX; t++) {
        double f = (double)t * inv;
        float c = (float)std::cos(f), s = (float)std::sin(f);
        cs[(size_t)t * 64 + i] = c; sn[(size_t)t * 64 + i] = s;
        csT[(size_t)i * TMAX + t] = c; csT[(size_t)(i + 64) * TMAX + t] = c;
        snT[(size_t)i * TMAX + t] = s; snT[(size_t)(i + 64) * TMAX + t] = s;
      }
    }
    dev.write("cos", cs.data(), cs.size() * 4); dev.write("sin", sn.data(), sn.size() * 4);
    dev.write("cosT", csT.data(), csT.size() * 4); dev.write("sinT", snT.data(), snT.size() * 4);
  }

  void init(const std::string& dir) {
    load_weights(dir);
    // state: caches must hold finite values (zero once); token history, prompt, positions
    dev.zero("kcache", (size_t)L * 2 * 4 * 128 * TMAX * 2);
    dev.zero("vcache", (size_t)L * 2 * TMAX * 512 * 2);
    dev.zero("toks", (size_t)(TMAX + 1) * 4);
    dev.zero("prompt", (size_t)TMAX * 4);
    dev.zero("plen", 4); dev.zero("plen_pf", 4); dev.zero("posX", 4); dev.zero("posY", 4);
    const size_t S = PREFILL_MAX;
    dev.zero("ids", S * 4);
    dev.zero("s_h", 128 * 8 * S * 4); dev.zero("s_q", 16 * 128 * S * 2); dev.zero("s_k", 8 * 128 * S * 2);
    dev.zero("s_v", 8 * S * 128 * 2); dev.zero("s_o", 16 * 128 * S * 2); dev.zero("s_a", 24 * 128 * S * 2);
    for (int b : STEP_BUCKETS) {
      std::string n = "step_b" + std::to_string(b);
      // kcw / vcw: the kernel's write-only names for the caches, bound to the same device tensors
      stepA[b] = bind(n, -1, {{"pos", "posX"}, {"output_0", "posY"}, {"kcw", "kcache"}, {"vcw", "vcache"}});
      stepB[b] = bind(n, -1, {{"pos", "posY"}, {"output_0", "posX"}, {"kcw", "kcache"}, {"vcw", "vcache"}});
    }
    for (int s : PREFILL_BUCKETS) {
      std::string sfx = "_S" + std::to_string(s);
      std::map<std::string, std::string> rn = {{"plen", "plen_pf"}, {"output_0", "posX"}};
      auto& v = prefill[s];
      v.push_back(bind("pf_emb" + sfx, -1, rn));
      // buckets <= SB_MAX: the SBUF-resident layer (prefill_sb.py, decode weight layouts); else the phased one
      const char* lay = s <= SB_MAX ? "pf_sb" : s <= SBC_MAX ? "pf_sbc" : "pf_layer";
      for (int l = 0; l < L - 1; l++) v.push_back(bind(lay + sfx, l, rn));
      // last layer: its KV cache writes for every prompt token (pf_kv), then the rest of it for the last token only,
      // the LM head and the argmax (pf_tail, the decode layer code at pos = plen - 1)
      v.push_back(bind("pf_kv" + sfx, L - 1, rn));
      std::map<std::string, std::string> rt = rn;
      rt["kcw"] = "kcache"; rt["vcw"] = "vcache";
      v.push_back(bind("pf_tail" + sfx, -1, rt));
    }
    // one throwaway request so that first-execution costs are paid before hello returns
    // (prompt lengths chosen so that every prefill bucket and every decode bucket runs once)
    for (int n : {256, 400, 600, 1024, 1200, 1600, 2500, 4096, 4300}) {
      std::vector<int> w(n); for (int i = 0; i < n; i++) w[i] = (int)(((int64_t)i * 7919 + 13) % VOCAB);
      generate(w, 2, true);
    }
    pos = -1;
  }

  // queue helpers
  nrta_seq_t last = 0;
  void submit(const Exec& e) {
    rets.push_back(NRT_SUCCESS);
    NRT_STATUS s;
    while ((s = nrta_execute_schedule(e.m, e.in, e.out, 0, &rets.back(), &last)) == NRT_QUEUE_FULL) {}
    CK(s);
  }
  void wait() {
    bool done = false;
    while (!done) CK(nrta_is_completed(last, &done));
    for (auto r : rets) if (r != NRT_SUCCESS) throw std::runtime_error(std::string("execution failed: ") + nrt_get_status_as_str(r));
    rets.clear();
  }
  void step() {   // one decode step at host-known position `pos`
    int b = 0;
    for (int x : STEP_BUCKETS) if (pos < x) { b = x; break; }
    if (!b) throw std::runtime_error("position beyond the largest attention bucket");
    submit(posInX ? stepA[b] : stepB[b]);
    posInX = !posInX; pos++;
  }

  std::vector<int> generate(const std::vector<int>& prompt, int n, bool reset) {
    if (n < 1) return {};
    rets.reserve(TMAX + 64);   // statuses are written asynchronously: no reallocation while in flight
    int first;                 // index in toks of the first token of the reply
    if (reset) {
      int P = prompt.size();
      if (P < 1) throw std::runtime_error("empty prompt");
      if (P + n > TMAX) throw std::runtime_error("prompt + max_tokens exceeds " + std::to_string(TMAX) + " positions");
      for (int t : prompt) if (t < 0 || t >= VOCAB) throw std::runtime_error("token id out of range");
      int pp = std::min(P, PREFILL_MAX);
      int S = 0; for (int s : PREFILL_BUCKETS) if (pp <= s) { S = s; break; }
      CK(nrt_tensor_write(dev.t["ids"], prompt.data(), 0, (size_t)pp * 4));
      CK(nrt_tensor_write(dev.t["prompt"], prompt.data(), 0, (size_t)P * 4));
      CK(nrt_tensor_write(dev.t["plen_pf"], &pp, 0, 4));
      CK(nrt_tensor_write(dev.t["plen"], &P, 0, 4));
      for (auto& e : prefill[S]) submit(e);
      pos = pp; posInX = true;                 // prefill wrote toks[pp] and posX = pp
      while (pos < P) step();                  // prompt tokens beyond the prefill bucket, one step each
      for (int i = 1; i < n; i++) step();
      first = P;
    } else {
      if (pos < 0) throw std::runtime_error("no state to continue");
      if (pos + n > TMAX) throw std::runtime_error("continuation exceeds " + std::to_string(TMAX) + " positions");
      first = pos + 1;
      for (int i = 0; i < n; i++) step();
    }
    wait();
    std::vector<int> out(n);
    CK(nrt_tensor_read(dev.t["toks"], out.data(), (size_t)first * 4, (size_t)n * 4));
    for (int& t : out) if (t < 0 || t >= VOCAB) throw std::runtime_error("device produced an invalid token id");
    return out;
  }
};

// Request lines from stdin. Between requests the reader spins on a non-blocking stdin for up to SPIN_S seconds
// after the last input before it blocks in poll(). Measured (session 002, interleaved, cores swapped): a process
// that blocked in read() between requests took 5.55 / 15.07 / 65.77 ms for generate(P, 1) at P = 256 / 1,024 /
// 4,096, the spinning one 5.28 / 14.58 / 64.16 ms (the host's runtime thread drives the NEFF-to-NEFF transitions of
// a request, and a host CPU that went idle between requests is slower to do so).
static const double SPIN_S = 10.0;
static bool read_line(std::string& line) {
  static std::string buf;
  static bool eof = false, nb = false;
  if (!nb) { fcntl(0, F_SETFL, fcntl(0, F_GETFL) | O_NONBLOCK); nb = true; }
  auto t0 = std::chrono::steady_clock::now();
  while (true) {
    size_t k = buf.find('\n');
    if (k != std::string::npos) { line = buf.substr(0, k); buf.erase(0, k + 1); return true; }
    if (eof) { if (buf.empty()) return false; line.swap(buf); buf.clear(); return true; }
    char tmp[1 << 16];
    ssize_t r = ::read(0, tmp, sizeof tmp);
    if (r > 0) { buf.append(tmp, r); t0 = std::chrono::steady_clock::now(); continue; }
    if (r == 0) { eof = true; continue; }
    if (errno != EAGAIN && errno != EWOULDBLOCK && errno != EINTR) { eof = true; continue; }
    if (std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count() > SPIN_S) {
      struct pollfd pf = {0, POLLIN, 0};
      poll(&pf, 1, -1);
    }
  }
}

// Replies go to a private duplicate of the original stdout; fd 1 itself is pointed at stderr before the runtime starts,
// because libnrt prints its log lines (e.g. configuration warnings) to stdout, which would corrupt the protocol.
static FILE* g_out = nullptr;
static void reply(const std::string& s) { fwrite(s.data(), 1, s.size(), g_out); fputc('\n', g_out); fflush(g_out); }
static std::string jstr(const std::string& s) {
  std::string r = "\"";
  for (char c : s) { if (c == '"' || c == '\\') { r += '\\'; r += c; } else if ((unsigned char)c < 0x20) r += ' '; else r += c; }
  return r + "\"";
}

int main(int argc, char** argv) {
  std::string model;
  for (int i = 1; i < argc; i++) if (!strcmp(argv[i], "--model") && i + 1 < argc) model = argv[++i];
  if (model.empty()) die("usage: engine --model MODEL_DIR");
  {
    int fd = dup(1);
    if (fd < 0 || !(g_out = fdopen(fd, "w"))) die("cannot duplicate stdout");
    fflush(stdout);
    dup2(2, 1);
  }
  // use only the first visible logical NeuronCore
  if (const char* v = getenv("NEURON_RT_VISIBLE_CORES")) {
    std::string s = v; size_t k = s.find_first_of("-,");
    if (k != std::string::npos) setenv("NEURON_RT_VISIBLE_CORES", s.substr(0, k).c_str(), 1);
  }
  std::unique_ptr<Engine> eng;
  std::string line;
  while (read_line(line)) {
    if (line.empty()) continue;
    long long id = 0;
    try {
      JVal r = parse_json(line.data(), line.size());
      if (const JVal* x = r.get("id")) id = (long long)x->n;
      const JVal* op = r.get("op");
      std::string o = op ? op->s : "";
      if (o == "hello") {
        if (!eng) {
          CK(nrt_init(NRT_FRAMEWORK_TYPE_NO_FW, "", ""));
          eng.reset(new Engine());
          eng->init(model);
        }
        reply("{\"id\": " + std::to_string(id) + ", \"ok\": true, \"protocol\": 1}");
      } else if (o == "generate") {
        if (!eng) throw std::runtime_error("generate before hello");
        std::vector<int> prompt;
        if (const JVal* p = r.get("prompt")) for (auto& t : p->a) prompt.push_back((int)t.n);
        const JVal* mt = r.get("max_tokens"); const JVal* rs = r.get("reset");
        int n = mt ? (int)mt->n : 1; bool reset = rs ? rs->b : true;
        std::vector<int> toks = eng->generate(prompt, n, reset);
        std::string s = "{\"id\": " + std::to_string(id) + ", \"ok\": true, \"tokens\": [";
        for (size_t i = 0; i < toks.size(); i++) { if (i) s += ", "; s += std::to_string(toks[i]); }
        reply(s + "]}");
      } else {
        throw std::runtime_error("unknown op " + o);
      }
    } catch (const std::exception& ex) {
      fprintf(stderr, "engine: request %lld: %s\n", id, ex.what()); fflush(stderr);
      reply("{\"id\": " + std::to_string(id) + ", \"ok\": false, \"error\": " + jstr(ex.what()) + "}");
    }
  }
  if (eng) nrt_close();
  return 0;
}
