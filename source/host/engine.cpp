// Model constants (Qwen3-0.6B) and the kernels' layouts
static const int L = 28, HID = 1024, VOCAB = 151936, TMAX = 4608, NVL = 594;
static const int STEP_BUCKETS[] = {384, 512, 1024, 1152, 1536, 2048, 3072, 4224, 4608};
static const int PREFILL_BUCKETS[] = {256, 1024, 4096};
static const int PREFILL_MAX = 4096;
static const int SB_MAX = 256, SBC_MAX = 1024;   // must match tools/build_neffs.py

static void die(const std::string& m) { fprintf(stderr, "engine: %s\n", m.c_str()); fflush(stderr); exit(1); }
#define CK(x) do { NRT_STATUS s_ = (x); if (s_ != NRT_SUCCESS) \
  throw std::runtime_error(std::string(#x) + " -> " + nrt_get_status_as_str(s_)); } while (0)

